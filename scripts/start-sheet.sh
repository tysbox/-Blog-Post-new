#!/usr/bin/env bash
#
# カルタ / 用語集のスプレッドシート型エディタを起動するランチャー。
#
#   - scripts/start-sheet.sh : 本体（どのターミナルからでも実行できる）
#   - start-sheet.command    : Finder からダブルクリックするための入口（リポジトリ直下）
#
# 手順:
#   1. .nvmrc の Node を解決する（scripts/lib/node-env.sh に集約）
#   2. node_modules が解決できることを確認する（壊れていれば npm ci を案内）
#   3. スプレッドシート型エディタを起動する（既定 http://127.0.0.1:4322）
#
# ブラウザは自動で開きません（SHEET_NO_OPEN=1 を常に付与）。
# 既に開いているタブを再読込して使ってください。
#
# 使い分け:
#   - ターミナルから : npm run sheet
#   - Finder から   : start-sheet.command をダブルクリック
#
# 環境変数:
#   SHEET_PORT=4400 … 待ち受けポートを変更する（既定 4322）
#
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}" || exit 1

HOST="127.0.0.1"
PORT="${SHEET_PORT:-4322}"
BASE_URL="http://${HOST}:${PORT}"

# ---------------------------------------------------------------------------
# 0) 共通の下準備（PATH 補完 / Node 解決 / ログ関数）
# ---------------------------------------------------------------------------
# shellcheck source=lib/node-env.sh
. "${REPO_ROOT}/scripts/lib/node-env.sh"

bold "=== カルタ / 用語集 スプレッドシートを開始します ==="
info "作業ディレクトリ: ${REPO_ROOT}"

# ---------------------------------------------------------------------------
# 1) node_modules の確認
#    このアプリは Node 標準モジュールだけで動くため、依存の同期までは行わない。
#    ただし node_modules が壊れていると他の作業に影響するため、解決できない
#    場合だけ案内して停止する。
# ---------------------------------------------------------------------------
if [ ! -d node_modules ]; then
  fail "node_modules を解決できませんでした。"
  fail "先に start.command（または npm ci）を実行してから再試行してください。"
  exit 1
fi

# ---------------------------------------------------------------------------
# 2) 既に起動していればそのまま終了する
# ---------------------------------------------------------------------------
if curl -sf -o /dev/null --max-time 2 "${BASE_URL}/api/state"; then
  info "スプレッドシート型エディタは既に起動しています（${BASE_URL}）"
  exit 0
fi

# --- 2.5) ポート占有ガード -------------------------------------------------
# 別プロセスがポートを掴んでいる場合、後段の起動は EADDRINUSE で失敗する。
# 原因を明示して停止する。
if command -v lsof >/dev/null 2>&1 && lsof -nP -iTCP:"${PORT}" -sTCP:LISTEN >/dev/null 2>&1; then
  warn "ポート ${PORT} は別のプロセスが使用中です。"
  lsof -nP -iTCP:"${PORT}" -sTCP:LISTEN | sed -n '2p' >&2 || true
  fail "該当プロセスを停止するか、SHEET_PORT=4400 のように変更して再実行してください。"
  exit 1
fi

# ---------------------------------------------------------------------------
# 3) 起動（ブラウザは開かない）
# ---------------------------------------------------------------------------
bold "--- スプレッドシート型エディタ（Ctrl+C で停止）---"
info "URL: ${BASE_URL}/"
info "ブラウザは自動で開きません（開いているタブを再読込してください）"

SHEET_NO_OPEN=1 SHEET_PORT="${PORT}" npm run sheet

bold "--- スプレッドシート型エディタを停止しました ---"
